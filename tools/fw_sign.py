#!/usr/bin/env python3
"""Sign and verify firmware package manifests: ECDSA P-256 over SHA-256 of the
exact bytes of manifest.json, DER-encoded -- what mbedtls_pk_verify() checks on
the device (main/fw_verify.cpp).

Everything goes through the openssl CLI: it is on every CI runner and developer
machine already, so signing needs no Python package.

  fw_sign.py pubkey-header -o main/fw_sign_pubkey.h [PUB.pem ...]    (0..2 keys)
  fw_sign.py verify-header main/fw_sign_pubkey.h manifest.json manifest.sig

The private key lives only in the Actions secret FW_SIGNING_KEY.
docs/subsystems/firmware-updates.md
"""
import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

MAX_KEYS = 2
P256_CURVE_LINE = re.compile(r"^ASN1 OID: prime256v1$", re.M)
BYTES_PER_LINE = 12
FINGERPRINT_HEX = 16


def _openssl(*args: str) -> bytes:
    r = subprocess.run(["openssl", *args], capture_output=True)
    if r.returncode != 0:
        raise SystemExit(f"openssl {args[0]}: {r.stderr.decode(errors='replace').strip()}")
    return r.stdout


def _require_p256(key: Path, public: bool) -> None:
    text = _openssl("pkey", *(["-pubin"] if public else []), "-in", str(key), "-noout", "-text").decode()
    if not P256_CURVE_LINE.search(text):
        raise SystemExit(f"{key}: not an ECDSA P-256 key")


def public_der(pub_pem: Path) -> bytes:
    """SubjectPublicKeyInfo DER -- what mbedtls_pk_parse_public_key() reads."""
    _require_p256(pub_pem, public=True)
    return _openssl("pkey", "-pubin", "-in", str(pub_pem), "-outform", "DER")


def verify(manifest: Path, sig: bytes, pub_pem: Path) -> bool:
    with tempfile.TemporaryDirectory() as tmp:
        sig_path = Path(tmp) / "manifest.sig"
        sig_path.write_bytes(sig)
        r = subprocess.run(["openssl", "dgst", "-sha256", "-verify", str(pub_pem), "-signature",
                            str(sig_path), str(manifest)], capture_output=True)
        return r.returncode == 0


def sign(manifest: Path, key_pem: Path) -> bytes:
    _require_p256(key_pem, public=False)
    sig = _openssl("dgst", "-sha256", "-sign", str(key_pem), str(manifest))
    with tempfile.TemporaryDirectory() as tmp:
        pub = Path(tmp) / "pub.pem"
        pub.write_bytes(_openssl("pkey", "-in", str(key_pem), "-pubout"))
        if not verify(manifest, sig, pub):
            raise SystemExit("signature does not verify with its own key")
    return sig


def header_text(ders: list[bytes]) -> str:
    if len(ders) > MAX_KEYS:
        raise SystemExit(f"at most {MAX_KEYS} keys: one in use, one announced for rotation")
    fingerprints = " ".join(hashlib.sha256(d).hexdigest()[:FINGERPRINT_HEX] for d in ders) or "(none)"
    out = [
        "/* Generated by tools/fw_sign.py pubkey-header from the .pub.pem files in config/fw_signing -- do not edit.",
        " * Public keys a package's manifest.sig may verify with (ECDSA P-256, DER",
        " * SubjectPublicKeyInfo). Two slots: a new key ships one release before CI",
        " * signs with it. C++ only; included by main/fw_verify.cpp alone.",
        " * docs/subsystems/firmware-updates.md",
        f" * keys: {fingerprints} */",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct FwSignKey {",
        "    const uint8_t *der;",
        "    size_t len;",
        "};",
        "",
    ]
    for i, der in enumerate(ders):
        out.append(f"static const uint8_t kFwSignKey{i}[] = {{")
        for off in range(0, len(der), BYTES_PER_LINE):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in der[off:off + BYTES_PER_LINE]) + ",")
        out.append("};")
        out.append("")
    out.append(f"#define FW_SIGN_KEY_COUNT {len(ders)}")
    out.append("")
    out.append(f"static const FwSignKey kFwSignKeys[{MAX_KEYS}] = {{")
    for i in range(MAX_KEYS):
        out.append(f"    {{kFwSignKey{i}, sizeof(kFwSignKey{i})}}," if i < len(ders) else "    {nullptr, 0},")
    out.append("};")
    return "\n".join(out) + "\n"


def header_keys(text: str) -> list[bytes]:
    keys = []
    for m in re.finditer(r"static const uint8_t kFwSignKey\d+\[\] = \{(.*?)\};", text, re.S):
        keys.append(bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1))))
    return keys


def verify_with_header(header: Path, manifest: Path, sig: bytes) -> bool:
    for der in header_keys(Path(header).read_text()):
        with tempfile.TemporaryDirectory() as tmp:
            der_path = Path(tmp) / "pub.der"
            der_path.write_bytes(der)
            pem = Path(tmp) / "pub.pem"
            pem.write_bytes(_openssl("pkey", "-pubin", "-inform", "DER", "-in", str(der_path)))
            if verify(manifest, sig, pem):
                return True
    return False


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    h = sub.add_parser("pubkey-header", help="write main/fw_sign_pubkey.h from public keys")
    h.add_argument("-o", "--out", required=True)
    h.add_argument("pems", nargs="*")
    v = sub.add_parser("verify-header", help="does a key in the header verify this signature?")
    v.add_argument("header")
    v.add_argument("manifest")
    v.add_argument("sig")
    a = ap.parse_args()
    if a.cmd == "pubkey-header":
        Path(a.out).write_text(header_text([public_der(Path(p)) for p in sorted(a.pems)]))
        print(a.out)
        return 0
    ok = verify_with_header(Path(a.header), Path(a.manifest), Path(a.sig).read_bytes())
    print("verified" if ok else "NOT verified by any key in the header")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
